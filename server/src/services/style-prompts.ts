async function migrateStyleSeeds(): Promise<void> {
  try {
    const flag = await prisma.setting.findUnique({ where: { k: LEGACY_SEED_KEY } });
    if (flag?.v === '2') return;

    const paraUpgrades: Record<string, string> = {
      星座: SPEC_PARA_ZODIAC,
      育儿: SPEC_PARA_LIST,
      激励: SPEC_PARA_LIST,
    };
    const changed: string[] = [];
    for (const [track, nextPara] of Object.entries(paraUpgrades)) {
      const key = specKey(track);
      const row = await prisma.stylePrompt.findUnique({ where: { key } });
      const text = row?.prompt ?? '';
      const idx = text.indexOf(LEGACY_PARA_BLOCK);
      if (idx < 0) continue;
      const next = text.slice(0, idx) + nextPara + text.slice(idx + LEGACY_PARA_BLOCK.length);
      await prisma.stylePrompt.update({ where: { key }, data: { prompt: next } });
      changed.push(key);
    }

    const zKey = variantKey('星座', 'length');
    const zRow = await prisma.stylePrompt.findUnique({ where: { key: zKey } });
    const zNew = (DEFAULT_VARIANT_LINES.星座?.length ?? []).join('\n---\n');
    if (zRow && zNew && zRow.prompt.trim() === LEGACY_ZODIAC_LENGTH) {
      await prisma.stylePrompt.update({ where: { key: zKey }, data: { prompt: zNew } });
      changed.push(zKey);
    }

    await prisma.setting.upsert({
      where: { k: LEGACY_SEED_KEY },
      create: { k: LEGACY_SEED_KEY, v: '2', kind: 'json', desc: '文风种子版本' },
      update: { v: '2' },
    });
    if (changed.length > 0) logger.info({ changed }, '文风种子已升级到 v2（段落形态 / 星座篇幅）');
  } catch {
    // 迁移失败不阻断：最坏情况是这条赛道沿用旧段落规范，不影响写稿链路。
  }
}

