/** 删除一条配置。'global' 是总纲，拒绝删除（想清空就改成默认文案）。 */
export async function deleteStylePrompt(key: string): Promise<void> {
  if (key === GLOBAL_KEY) {
    throw new Error('创作总纲（global）不可删除，可在配置页改写或恢复默认');
  }
  await prisma.stylePrompt.delete({ where: { key } });
}

/** 某 key 的出厂默认值（配置页「恢复默认」用）。无默认的自定义行返回 null。 */
export function defaultFor(key: string): { kind: StylePromptKind; prompt: string } | null {
  if (key === GLOBAL_KEY) return { kind: 'global', prompt: DEFAULT_GLOBAL_PROMPT };
  if (key.startsWith(SYS_PREFIX)) {
    const prompt = DEFAULT_SYSTEM_PROMPTS[key.slice(SYS_PREFIX.length)];
    return prompt ? { kind: 'system', prompt } : null;
  }
  if (key.startsWith(SPEC_PREFIX)) {
    const prompt = DEFAULT_TRACK_SPECS[key.slice(SPEC_PREFIX.length)];
    return prompt ? { kind: 'spec', prompt } : null;
  }
  if (key.startsWith(RULE_PREFIX)) {
    const rule = DEFAULT_TRACK_RULES[key.slice(RULE_PREFIX.length)];
    return rule ? { kind: 'rule', prompt: JSON.stringify(rule, null, 2) } : null;
  }
  const pv = parseVariantKey(key);
  if (pv) {
    const lines = DEFAULT_VARIANT_LINES[pv.track]?.[pv.dim];
    return lines ? { kind: 'variant', prompt: lines.join('\n---\n') } : null;
  }
  const prompt = DEFAULT_TRACK_PROMPTS[key];
  return prompt ? { kind: 'track', prompt } : null;
}

/** 全部出厂默认值（配置页整体预览/引导用）。 */
export function allDefaults(): {
  global: string;
  systems: Record<string, string>;
  tracks: Record<string, string>;
  variants: Record<string, string>;
  specs: Record<string, string>;
  rules: Record<string, string>;
} {
  const systems: Record<string, string> = {};
  for (const [track, prompt] of Object.entries(DEFAULT_SYSTEM_PROMPTS)) {
    systems[sysKey(track)] = prompt;
  }
  const variants: Record<string, string> = {};
  for (const [track, dims] of Object.entries(DEFAULT_VARIANT_LINES)) {
    for (const [dim, lines] of Object.entries(dims)) {
      if (lines && lines.length > 0) variants[variantKey(track, dim as VariantDim)] = lines.join('\n---\n');
    }
  }
  const rules: Record<string, string> = {};
  for (const [track, rule] of Object.entries(DEFAULT_TRACK_RULES)) {
    rules[ruleKey(track)] = JSON.stringify(rule, null, 2);
  }
  return {
    global: DEFAULT_GLOBAL_PROMPT,
    systems,
    tracks: { ...DEFAULT_TRACK_PROMPTS },
    variants,
    specs: { ...DEFAULT_TRACK_SPECS },
    rules,
  };
}
