/** 从变体行解析篇幅档：`min-max|pMin-pMax|说明`。解析失败返回 null（调用方回退默认锚）。 */
export function parseLengthLine(
  line: string,
): { min: number; max: number; pMin: number; pMax: number; note: string } | null {
  const m = /^(\d+)-(\d+)\|(\d+)-(\d+)\|(.+)$/.exec(line.trim());
  if (!m) return null;
  const min = Number(m[1] ?? 0);
  const max = Number(m[2] ?? 0);
  const pMin = Number(m[3] ?? 0);
  const pMax = Number(m[4] ?? 0);
  if (!(min > 0 && max > min && pMin > 0 && pMax >= pMin)) return null;
  return { min, max, pMin, pMax, note: (m[5] ?? '').trim() };
}

export function variantKey(track: string, dim: VariantDim): string {
  return `v:${track}:${dim}`;
}

/** 变体 key 的解析：'v:{track}:{dim}' → 各段；非法返回 null。 */
export function parseVariantKey(
  key: string,
): { track: string; dim: VariantDim } | null {
  if (!key.startsWith('v:')) return null;
  const rest = key.slice(2);
  const i = rest.lastIndexOf(':');
  if (i <= 0) return null;
  const track = rest.slice(0, i);
  const dim = rest.slice(i + 1) as VariantDim;
  if (!VARIANT_DIMS.includes(dim)) return null;
  return { track, dim };
}

function kindOf(key: string): StylePromptKind {
  if (key === GLOBAL_KEY) return 'global';
  if (key.startsWith(SYS_PREFIX)) return 'system';
  if (key.startsWith(SPEC_PREFIX)) return 'spec';
  if (key.startsWith(RULE_PREFIX)) return 'rule';
  return parseVariantKey(key) ? 'variant' : 'track';
}

function toRow(r: { key: string; kind: string; prompt: string; updatedAt: Date }): StylePromptRow {
  return {
    key: r.key,
    kind: kindOf(r.key),
    prompt: r.prompt,
    updatedAt: r.updatedAt.toISOString(),
  };
}

function seedData(): { key: string; kind: string; prompt: string }[] {
  const out: { key: string; kind: string; prompt: string }[] = [
    { key: GLOBAL_KEY, kind: 'global', prompt: DEFAULT_GLOBAL_PROMPT },
  ];
  for (const [track, prompt] of Object.entries(DEFAULT_SYSTEM_PROMPTS)) {
    out.push({ key: sysKey(track), kind: 'system', prompt });
  }
  for (const [key, prompt] of Object.entries(DEFAULT_TRACK_PROMPTS)) {
    out.push({ key, kind: 'track', prompt });
  }
  for (const [track, prompt] of Object.entries(DEFAULT_TRACK_SPECS)) {
    out.push({ key: specKey(track), kind: 'spec', prompt });
  }
  for (const [track, rule] of Object.entries(DEFAULT_TRACK_RULES)) {
    out.push({ key: ruleKey(track), kind: 'rule', prompt: JSON.stringify(rule, null, 2) });
  }
  for (const [track, dims] of Object.entries(DEFAULT_VARIANT_LINES)) {
    for (const [dim, lines] of Object.entries(dims)) {
      if (!lines || lines.length === 0) continue;
      // 变体之间用 `---` 分隔存库，这样一条变体可以是多行骨架卡；单行变体也照样成立
      // （只有一条时不含 `---`，解析时退回按行，行为与旧数据一致）。
      out.push({ key: variantKey(track, dim as VariantDim), kind: 'variant', prompt: lines.join('\n---\n') });
    }
  }
  return out;
}

/**
 * `sys:` 家族的一次性回填标记。
 *
 * 为什么需要它：`ensureStylePromptsSeeded` 只在**整表为空**时播种，而 2026-11-12 之前
 * 已上线的库早就有 `global` / 赛道 / 变体行了，`sys:{赛道}` 一条都不会被写进去，
 * 配置页也就看不到、改不了——「提示词能在页面配置」这件事会静默失效。
 *
 * 为什么只回填一次而不是每次补齐：删掉某条 `sys:{赛道}` 是**有意义**的操作
 * （= 这条赛道改用通用模板），每次自动补回来会让人删不掉。所以用 Setting 打标。
 */
const SYS_BACKFILL_KEY = 'style_sys_backfilled';

async function backfillSystemPrompts(): Promise<void> {
  try {
    const flag = await prisma.setting.findUnique({ where: { k: SYS_BACKFILL_KEY } });
    if (flag?.v === '1') return;
    const rows = await prisma.stylePrompt.findMany({
      where: { key: { startsWith: SYS_PREFIX } },
      select: { key: true },
    });
    const existing = new Set(rows.map((r) => r.key));
    const missing = Object.entries(DEFAULT_SYSTEM_PROMPTS)
      .map(([track, prompt]) => ({ key: sysKey(track), kind: 'system', prompt }))
      .filter((x) => !existing.has(x.key));
    if (missing.length > 0) await prisma.stylePrompt.createMany({ data: missing });
    await prisma.setting.upsert({
      where: { k: SYS_BACKFILL_KEY },
      create: { k: SYS_BACKFILL_KEY, v: '1', kind: 'json', desc: '系统提示词已回填' },
      update: { v: '1' },
    });
    if (missing.length > 0) {
      logger.info({ added: missing.map((m) => m.key) }, '系统提示词已回填到配置表');
    }
  } catch {
    // 回填失败不影响写稿：loadSystemPrompt 有代码种子兜底。
  }
}

