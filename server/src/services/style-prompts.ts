/** 把一份模板文本按 `## system` / `## tail` 切开。缺节返回空串，渲染层会补兜底。 */
export function parseSystemTemplate(text: string): { system: string; tail: string } {
  const { sections } = parseSpecSections(text);
  const pick = (...names: string[]): string => {
    for (const n of names) {
      const v = sections[n]?.trim();
      if (v) return v;
    }
    return '';
  };
  return { system: pick('system', 'System', 'SYSTEM'), tail: pick('tail', 'Tail', 'TAIL') };
}

/**
 * 读某赛道的系统提示词模板。
 *
 * 回落顺序（这个顺序是有意的，别调）：
 *   `sys:{赛道}` → `sys:default` → 代码种子
 * 赛道那一行被删掉 = 这条赛道改用通用模板，所以**不再回落到该赛道的代码种子**
 * ——否则删除操作会被代码悄悄复活，配置页就永远删不掉。
 * 代码种子只在读库异常（DB 不可用）时兜底，保证写稿链路不会因为配置挂掉。
 */
export async function loadSystemPrompt(track: string): Promise<TrackSystemPrompt> {
  try {
    for (const key of [sysKey(track), sysKey(SYS_DEFAULT_TRACK)]) {
      const row = await getStylePrompt(key);
      const text = row?.prompt?.trim();
      if (text) {
        const t = parseSystemTemplate(text);
        if (t.system) return { ...t, fromDb: true, sourceKey: key };
      }
    }
  } catch {
    // 落到代码种子
  }
  const seedText = DEFAULT_SYSTEM_PROMPTS[track] ?? DEFAULT_SYSTEM_PROMPTS[SYS_DEFAULT_TRACK] ?? '';
  return {
    ...parseSystemTemplate(seedText),
    fromDb: false,
    sourceKey: `code:${DEFAULT_SYSTEM_PROMPTS[track] ? track : SYS_DEFAULT_TRACK}`,
  };
}

/**
 * 写稿用的赛道配置装载：总纲 + 赛道文体 + 写作规范 + 机器规则 + 系统提示词。
 *
 * 2026-11-11 起 `config/style_dna.json` **不再参与运行时**（只作播种种子）。
 * 某赛道没配就回落到代码里的种子文本，所以读库失败也不会让写稿链路挂掉。
 */
export async function loadStyleForTrack(trackName: string): Promise<{
  globalPrompt?: string;
  trackPrompt?: string;
  spec: TrackSpec;
  rule: TrackRule;
  system: TrackSystemPrompt;
}> {
  try {
    const [global, track, spec, rule, system] = await Promise.all([
      getStylePrompt(GLOBAL_KEY),
      getStylePrompt(trackName),
      loadTrackSpec(trackName),
      loadTrackRule(trackName),
      loadSystemPrompt(trackName),
    ]);
    return {
      globalPrompt: global?.prompt?.trim() || undefined,
      trackPrompt: track?.prompt?.trim() || undefined,
      spec,
      rule,
      system,
    };
  } catch {
    const seedText = DEFAULT_SYSTEM_PROMPTS[trackName] ?? DEFAULT_SYSTEM_PROMPTS[SYS_DEFAULT_TRACK] ?? '';
    return {
      spec: { ...parseSpecSections(DEFAULT_TRACK_SPECS[trackName] ?? ''), fromDb: false },
      rule: ruleFor(trackName),
      system: {
        ...parseSystemTemplate(seedText),
        fromDb: false,
        sourceKey: `code:${DEFAULT_SYSTEM_PROMPTS[trackName] ? trackName : SYS_DEFAULT_TRACK}`,
      },
    };
  }
}

/** 题库扩库用：只取创作总纲。读库失败返回空串（扩库照常，只是少一层约束）。 */
export async function loadGlobalPrompt(): Promise<string> {
  try {
    const row = await getStylePrompt(GLOBAL_KEY);
    return row?.prompt?.trim() ?? '';
  } catch {
    return '';
  }
}

/**
 * 把一段变体文本切成条目。
 *
 * **优先按显式分隔符 `---` 切**（单独一行三条横线）——这样一条变体可以是一整张
 * 多行骨架卡。历史上没有分隔符，退回「一行一条」，因此旧数据解析结果完全不变。
 *
 * 为什么不能只按行切：2026-11-11 之前结构变体每条只能写一句话（40 字），
 * 模型拿不到「分几节 / 每节干什么 / 写哪几个星座」，只能自己发挥，最后套上通用
 * 骨架——这才是「写出来不像星座文章」的直接原因，不是没人愿意写详细。
 */
export function splitVariantBlocks(text: string): string[] {
  const blocks = text
    .split(/\n[ \t]*---[ \t]*\n/)
    .map((s) => s.trim())
    .filter(Boolean);
  if (blocks.length > 1) return blocks;
  return text
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean);
}

/** 读一个维度的变体行：赛道库优先，回落全局库，再回落代码内默认值。 */
async function loadVariantLines(track: string, dim: VariantDim): Promise<string[]> {
  const fallback = (): string[] => {
    const g = DEFAULT_VARIANT_LINES.global?.[dim] ?? [];
    return g.length > 0 ? g : [`默认${dim}变体（请在文风配置页补充）`];
  };
  try {
    for (const key of [variantKey(track, dim), variantKey(GLOBAL_KEY, dim)]) {
      const row = await getStylePrompt(key);
      const lines = splitVariantBlocks(row?.prompt ?? '');
      if (lines.length > 0) return lines;
    }
    return fallback();
  } catch {
    return fallback();
  }
}

/**
 * 把写作规范文本按 `## ` 切成小节。
 * 返回 `{ 小节名: 正文 }`，以及未分节的残余（历史数据可能没写 `##`）。
 */
export function parseSpecSections(text: string): { sections: Record<string, string>; loose: string } {
  const sections: Record<string, string> = {};
  const loose: string[] = [];
  let current: string | null = null;
  for (const line of text.split('\n')) {
    const m = /^##\s+(.+?)\s*$/.exec(line);
    if (m) {
      current = (m[1] ?? '').trim();
      sections[current] = '';
      continue;
    }
    if (current === null) {
      if (line.trim()) loose.push(line.trim());
    } else {
      const body = sections[current] ?? '';
      sections[current] = body ? `${body}\n${line}` : line;
    }
  }
  for (const k of Object.keys(sections)) sections[k] = (sections[k] ?? '').trim();
  return { sections, loose: loose.join('\n') };
}

export interface TrackSpec {
  /** 小节名 → 正文。名称为中文（段落形态 / 强调标注 / 句式补充 / 去AI味（预留））。 */
  sections: Record<string, string>;
  /** 没有写 `##` 的历史数据落在里，按整段注入。 */
  loose: string;
  /** 是否来自数据库（false = 用的代码种子）。 */
  fromDb: boolean;
}

/** 读某赛道的写作规范。没有配就用种子，读库失败也用种子——写稿不能被配置拖死。 */
export async function loadTrackSpec(track: string): Promise<TrackSpec> {
  const seed = DEFAULT_TRACK_SPECS[track] ?? '';
  try {
    const row = await getStylePrompt(specKey(track));
    const text = row?.prompt?.trim();
    if (text) return { ...parseSpecSections(text), fromDb: true };
  } catch {
    // 落到种子
  }
  return { ...parseSpecSections(seed), fromDb: false };
}

/** 读某赛道的机器规则（体检项 / 选题形态 / 豁免项）。库里是 JSON；解析失败回落到种子。 */
export async function loadTrackRule(track: string): Promise<TrackRule> {
  const seed = ruleFor(track);
  try {
    const row = await getStylePrompt(ruleKey(track));
    const text = row?.prompt?.trim();
    if (text) {
      const parsed: unknown = JSON.parse(text);
      if (parsed && typeof parsed === 'object') {
        const o = parsed as Record<string, unknown>;
        const checks = Array.isArray(o.checks)
          ? o.checks.filter((c): c is string => typeof c === 'string')
          : [];
        const mode = o.angleMode === 'zodiac' ? 'zodiac' : 'default';
        // relax 是 2026-11-12 新增的字段：老库里 `r:{赛道}` 没有它，
        // 这时继承出厂默认（而不是当成空数组），否则新赛道的段落豁免对存量库永远不生效。
        // 想显式关掉豁免就写 `"relax": []`。
        const relax = Array.isArray(o.relax)
          ? o.relax.filter((c): c is string => typeof c === 'string')
          : seed.relax ?? [];
        return { checks, angleMode: mode, relax };
      }
    }
  } catch {
    // 落到种子
  }
  return seed;
}

// 变体游标：每写一篇 +1，三维各自取模，保证连续多篇组合不重样（周期 = 三维长度的最小公倍数）。
export const VARIANT_CURSOR_KEY = 'style_variant_cursor';

async function nextVariantCursor(track: string): Promise<number> {
  let map: Record<string, number> = {};
  try {
    const row = await prisma.setting.findUnique({ where: { k: VARIANT_CURSOR_KEY } });
    if (row?.v) map = JSON.parse(row.v) as Record<string, number>;
  } catch {
    map = {};
  }
  const n = (map[track] ?? 0) + 1;
  map[track] = n;
  // 只保留近 200 条赛道游标，防止设置行无限膨胀。
  const keys = Object.keys(map);
  if (keys.length > 200) for (const k of keys.slice(0, keys.length - 200)) delete map[k];
  await prisma.setting.upsert({
    where: { k: VARIANT_CURSOR_KEY },
    create: { k: VARIANT_CURSOR_KEY, v: JSON.stringify(map), kind: 'json', desc: '文风变体轮换游标' },
    update: { v: JSON.stringify(map) },
  });
  return n;
}

/**
 * 读各赛道已轮换到的游标（只读，不递增）。
 *
 * 配置页用它显示「下次写稿会取第几条」——轮换是看不见的，不显示就没人知道
 * 变体库到底在不在生效、条数少到什么程度会开始重复。读失败返回空对象，
 * 配置页少一行提示而已，不影响任何写稿链路。
 */
export async function getVariantCursors(): Promise<Record<string, number>> {
  try {
    const row = await prisma.setting.findUnique({ where: { k: VARIANT_CURSOR_KEY } });
    if (!row?.v) return {};
    const parsed: unknown = JSON.parse(row.v);
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return {};
    const out: Record<string, number> = {};
    for (const [track, n] of Object.entries(parsed as Record<string, unknown>)) {
      if (typeof n === 'number' && Number.isFinite(n) && n >= 0) out[track] = n;
    }
    return out;
  } catch {
    return {};
  }
}

export interface PickedVariants {
  /** 本次选用的标题公式（一条） */
  title: string;
  /** 本次选用的结构骨架（一条） */
  structure: string;
  /** 本次选用的篇幅档（原始行） */
  length: string;
  /** 解析出的篇幅锚；解析失败为 null（调用方回退 constants 默认值） */
  lengthTarget: { min: number; max: number; pMin: number; pMax: number; note: string } | null;
  /** 本次游标（日志/复现用） */
  cursor: number;
}

/**
 * 为一篇新稿取三维变体。轮换取模（游标每篇 +1），避免连续 N 篇同模板。
 * 取库失败也返回可用默认值——变体不能让写稿挂掉。
 */
export async function pickVariants(track: string): Promise<PickedVariants> {
  let cursor = 0;
  try {
    await ensureStylePromptsSeeded();
    cursor = await nextVariantCursor(track);
  } catch {
    cursor = Math.floor(Math.random() * 1000);
  }
  const [titles, structures, lengths] = await Promise.all([
    loadVariantLines(track, 'title'),
    loadVariantLines(track, 'structure'),
    loadVariantLines(track, 'length'),
  ]);
  // loadVariantLines 永不返回空数组；这里只为了满足 noUncheckedIndexedAccess。
  const at = (arr: string[]): string => arr[cursor % arr.length] ?? arr[0] ?? '';
  const lengthLine = at(lengths);
  return {
    title: at(titles),
    structure: at(structures),
    length: lengthLine,
    lengthTarget: parseLengthLine(lengthLine),
    cursor,
  };
}

